import random
def pedraPaperTisora():
  eines = ('pedra', 'paper', 'tisora')
  wJugador = 0
  wComp = 0

  while wJugador < 3 and wComp < 3:

    einaJugador = input('Introdueix que vols treure (pedra, paper, tisora): ').lower()

    einaComp = random.choice(eines)

    if einaJugador == einaComp:
      print('Empat!')
      print(f'Heu tret els dos {einaJugador}')

    elif (
        (einaJugador == 'pedra' and einaComp == 'tisora') or
        (einaJugador == 'tisora' and einaComp == 'paper') or
        (einaJugador == 'paper' and einaComp == 'pedra')):

      wJugador += 1
      print('Has guanyat!')
      print(f'Tu has tret {einaJugador} i la maquina {einaComp}')

    elif einaJugador not in eines:
      print('La opcio introduïda no es valida.')

    else:
      wComp += 1
      print('Has perdut!')
      print(f'Tu has tret {einaJugador} i la maquina {einaComp}')

    print(f'Contador victories (Millor de 3): \nJugador: {wJugador}, Maquina: {wComp}\n')

